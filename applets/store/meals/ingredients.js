export const PATHS = new Set(ITEMS.map(([, , path]) => path));
const BY_NAME = new Map();
for (const item of ITEMS) BY_NAME.set(item[0].toLocaleLowerCase("tr-TR"), item);
for (const item of ITEMS) {
  if (!item[1]) continue;
  for (const key of [item[1].toLocaleLowerCase("tr-TR"), item[1].toLowerCase()]) if (!BY_NAME.has(key)) BY_NAME.set(key, item);
}
const BY_TR_LENGTH = [...ITEMS].sort((a, b) => b[0].length - a[0].length);
const BY_EN_LENGTH = [...ITEMS].sort((a, b) => b[1].length - a[1].length);
const meta = (name) => BY_NAME.get(name.toLocaleLowerCase("tr-TR")) ?? BY_NAME.get(name.toLowerCase()) ?? null;

/** An ingredient name → its picture's "category/slug": the name itself, a catalog name inside it ("haşlanmış nohut" →
    Nohut), the English name inside it, else its longest word. */
export function ingredientPath(name) {
  const trimmed = String(name ?? "").trim();
  if (!trimmed) return null;
  const direct = meta(trimmed);
  if (direct) return direct[2];
  const lower = trimmed.toLocaleLowerCase("tr-TR");
  const tr = BY_TR_LENGTH.find((i) => i[0].length >= 3 && lower.includes(i[0].toLocaleLowerCase("tr-TR")));
  if (tr) return tr[2];
  const lowerEn = trimmed.toLowerCase();
  const en = BY_EN_LENGTH.find((i) => i[1].length >= 3 && lowerEn.includes(i[1].toLowerCase()));
  if (en) return en[2];
  const word = lower.split(/\s+/).filter((w) => w.length >= 3).sort((a, b) => b.length - a.length).map(meta).find(Boolean);
  return word ? word[2] : null;
}
