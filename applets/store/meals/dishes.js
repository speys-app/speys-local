const fold = (v) => String(v ?? "").toLocaleLowerCase("tr-TR").replace(/\s+/g, " ").trim();
const BY_NAME = new Map([...CATALOG.map(([name, slug]) => [fold(name), slug]), ...ALIASES]);
// The longest name first: "Tavuklu Pilav" is tried before "Pilav".
const KEYS = [...BY_NAME.keys()].sort((a, b) => b.length - a.length);
export const SLUGS = new Set(CATALOG.map(([, slug]) => slug));

/** The catalog picture for a dish name: an exact match, else the longest catalog name inside it, on word boundaries. */
export function dishSlug(title) {
  const key = fold(title);
  if (!key) return null;
  if (BY_NAME.has(key)) return BY_NAME.get(key);
  const padded = ` ${key} `;
  const hit = KEYS.find((k) => padded.includes(` ${k} `));
  return hit ? BY_NAME.get(hit) : null;
}

/** An emoji for a word in the title, when there's no picture. */
export function dishEmoji(title) {
  const t = String(title ?? "").trim().toLowerCase();
  return EMOJI.find(([word]) => t.includes(word))?.[1] ?? null;
}
